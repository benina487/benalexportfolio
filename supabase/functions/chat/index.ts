import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

const systemPrompt = `You are Benina A's portfolio assistant. You know the following about Benina:

- B.Tech student in AI & Data Science at Francis Xavier Engineering College, Tirunelveli (2023-2027), CGPA 9.5
- Skills: Python, Java, C, JavaScript, React, HTML/CSS, MySQL, MongoDB, Machine Learning, Computer Vision, Power BI, Tableau, Cybersecurity
- Internship: AI Engineer Intern at Clear Trust, Bangalore (Jul-Aug 2025) - developed voice biometric authentication
- Projects: Hawk Eye (access management), BioPulse (plant stress detection), Voice Biometric Auth, Landslide Detection IoT, Gold vs Silver Rate Dashboard, Mental Health Chatbot
- Contact: ben10alexantony@gmail.com, +91 8122072978, TamilNadu India
- LinkedIn: linkedin.com/in/benina-a-914025366, GitHub: github.com/benina487
- Certifications: MongoDB, NPTEL IoT, WsCube SQL, Microsoft Power BI

Be friendly, concise, and helpful. Answer questions about Benina's skills, projects, experience, and education. If asked something unrelated, politely redirect to portfolio topics.`;

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: systemPrompt },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limited, please try again later." }), {
          status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted." }), {
          status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
